const DIFFICULTY_KEYS: Record<string, string> = {
  "Boshlang'ich": 'filter.beginner',
  "O'rta": 'filter.intermediate',
  'Yuqori': 'filter.advanced',
};

type Translate = (key: string, fallback?: string) => string;

export function translateCategory(t: Translate, category: string): string {
  const key = CATEGORY_KEYS[category];
  return key ? t(key, category) : category;
}

export function translateDifficulty(t: Translate, difficulty: string): string {
  const key = DIFFICULTY_KEYS[difficulty];
  return key ? t(key, difficulty) : difficulty;
}

/** "15 daqiqa" -> "15 min" / "15分" etc., keeping the number intact. */
export function translateDuration(t: Translate, duration: string): string {
  const minutes = String(duration).match(/\d+/)?.[0];
  return minutes ? `${minutes} ${t('card.duration', 'daqiqa')}` : duration;
}

/** Languages written right-to-left; the document direction flips for these. */
const RTL_LANGUAGES = new Set(['ar', 'he', 'fa', 'ur', 'ps', 'ckb', 'dv', 'yi']);

export function isRtlLanguage(code: string): boolean {
  return RTL_LANGUAGES.has((code || '').toLowerCase().split(/[-_]/)[0]);
}

interface I18nContextType {
  currentUiLang: UiLanguageOption;
  availableUiLanguages: UiLanguageOption[];
  setUiLanguage: (code: string) => void;
  translateAndAddUiLanguage: (customLangName: string) => Promise<{ success: boolean; languageName: string; flag: string; engineUsed: string }>;
  t: (key: string, fallback?: string) => string;
  isTranslatingUi: boolean;
  lastTranslatedBy: string | null;
  /** True when the active UI language reads right-to-left. */
  isRtl: boolean;
}

const I18nContext = createContext<I18nContextType | null>(null);

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [currentUiLangCode, setCurrentUiLangCode] = useState<string>(() => {
    return localStorage.getItem('tiltop_ui_lang_code') || 'uz';
  });

  const [availableUiLanguages, setAvailableUiLanguages] = useState<UiLanguageOption[]>(() => {
    const saved = localStorage.getItem('tiltop_custom_ui_languages');
    if (saved) {
      try {
        const parsed = JSON.parse(saved);
        const merged = [...INITIAL_UI_LANGUAGES];
        parsed.forEach((custom: UiLanguageOption) => {
          if (!merged.some(l => l.code === custom.code)) {
            merged.push(custom);
          }
        });
        return merged;
      } catch (e) {}
    }
    return INITIAL_UI_LANGUAGES;
  });

  const [translationsCache, setTranslationsCache] = useState<Record<string, Record<string, string>>>(() => {
    const saved = localStorage.getItem('tiltop_translations_cache');
    if (saved) {
      try {
        // Built-ins must win. Spreading the cache last let a dictionary saved by
        // an earlier release replace a shipped one wholesale, so every key added
        // since then fell back to Uzbek — the UI simply stopped translating.
        // The cache exists only to carry AI-generated languages across reloads.
        return { ...JSON.parse(saved), ...BUILTIN_UI_TRANSLATIONS };
      } catch (e) {}
    }
    return BUILTIN_UI_TRANSLATIONS;
  });

  const [isTranslatingUi, setIsTranslatingUi] = useState(false);
  const [lastTranslatedBy, setLastTranslatedBy] = useState<string | null>(null);

  const isRtl = isRtlLanguage(currentUiLangCode);

  useEffect(() => {
    localStorage.setItem('tiltop_ui_lang_code', currentUiLangCode);
  }, [currentUiLangCode]);

  // Drive direction and lang from the document root so native text selection,
  // scrollbars, and logical CSS properties all follow the chosen language.
  useEffect(() => {
    document.documentElement.lang = currentUiLangCode;
    document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
  }, [currentUiLangCode, isRtl]);

  useEffect(() => {
    localStorage.setItem('tiltop_custom_ui_languages', JSON.stringify(
      availableUiLanguages.filter(l => l.isAiGenerated)
    ));
  }, [availableUiLanguages]);

  useEffect(() => {
    // Persist only AI-generated languages. Writing the built-ins back would
    // re-create the stale-cache problem the moment a new key ships.
    const customOnly: Record<string, Record<string, string>> = {};
    for (const code of Object.keys(translationsCache)) {
      if (!(code in BUILTIN_UI_TRANSLATIONS)) customOnly[code] = translationsCache[code];
    }
    localStorage.setItem('tiltop_translations_cache', JSON.stringify(customOnly));
  }, [translationsCache]);

  const setUiLanguage = (code: string) => {
    setCurrentUiLangCode(code);
  };

  const translateAndAddUiLanguage = async (customLangName: string) => {
    setIsTranslatingUi(true);
    try {
      const response = await fetch('/api/translate-ui', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          target_language: customLangName,
          base_dictionary: BASE_UZ_DICTIONARY,
        }),
      });

      if (!response.ok) {
        throw new Error('Failed to translate UI language');
      }

      const data = await response.json();
      const code = (data.language_name || customLangName).toLowerCase().replace(/[^a-z0-9]/g, '_').slice(0, 8);
      const newLangOption: UiLanguageOption = {
        code,
        name: data.language_name || customLangName,
        nativeName: data.native_name || customLangName,
        flag: data.flag || '🌐',
        isAiGenerated: true,
      };

      setAvailableUiLanguages(prev => {
        const filtered = prev.filter(l => l.code !== code);
        return [newLangOption, ...filtered];
      });

      setTranslationsCache(prev => ({
        ...prev,
        [code]: data.translations || {},
      }));

      setCurrentUiLangCode(code);
      setLastTranslatedBy(data._engineUsed || 'gemini');

      return {
        success: true,
        languageName: newLangOption.name,
        flag: newLangOption.flag,
        engineUsed: data._engineUsed || 'gemini',
      };
    } catch (err: any) {
      console.error('Translation error:', err);
      throw err;
    } finally {
      setIsTranslatingUi(false);
    }
  };

  const t = (key: string, fallback?: string): string => {
    const currentDict = translationsCache[currentUiLangCode];
    if (currentDict && currentDict[key]) {
      return currentDict[key];
    }
    if (translationsCache['uz'] && translationsCache['uz'][key]) {
      return translationsCache['uz'][key];
    }
    return fallback || BASE_UZ_DICTIONARY[key] || key;
  };

  const currentUiLang = availableUiLanguages.find(l => l.code === currentUiLangCode) || availableUiLanguages[0];

  return (
    <I18nContext.Provider
      value={{
        currentUiLang,
        availableUiLanguages,
        setUiLanguage,
        translateAndAddUiLanguage,
        t,
        isTranslatingUi,
        lastTranslatedBy,
        isRtl,
      }}
    >
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = (): I18nContextType => {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used within an I18nProvider');
  }
  return context;
};
